  const DICT = { en: EN, nl: NL };
  const LOCALES = { en: 'en-GB', nl: 'nl-NL' };
  let lang = 'en';
  const listeners = [];

  try {
    const saved = localStorage.getItem('hr.lang');
    if (saved && DICT[saved]) lang = saved;
    else if ((navigator.language || '').toLowerCase().startsWith('nl')) lang = 'nl';
  } catch (e) { /* ignore */ }

  function t(key, params) {
    let s = DICT[lang][key];
    if (s == null) s = DICT.en[key];
    if (s == null) return key;
    if (params) for (const p in params) s = s.split('{' + p + '}').join(params[p]);
    return s;
  }

  function setLang(l) {
    if (!DICT[l] || l === lang) return;
    lang = l;
    try { localStorage.setItem('hr.lang', l); } catch (e) { /* ignore */ }
    listeners.forEach(fn => fn(l));
  }

  HR.i18n = {
    t,
    setLang,
    get lang() { return lang; },
    get locale() { return LOCALES[lang]; },
    langs: [{ id: 'en', label: 'English' }, { id: 'nl', label: 'Nederlands' }],
    onChange: fn => listeners.push(fn),
    has: key => DICT[lang][key] != null || DICT.en[key] != null,
    DICT
  };
